// gen_words writes src/words_gen.c: Asuka's own words (internal/l10n's
// catalogs) as C tables, for the C desktop hosts. The Windows
// installer's (the keys installer*) aren't the hosts': its table is
// platform/windows/installer/words.h (internal/l10n's
// TestInstallerWords).
//
//	go run gen_words.go   (go generate ./platform/desktop)
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	dir := filepath.Join("..", "..", "internal", "l10n", "messages")
	files, err := filepath.Glob(filepath.Join(dir, "*.json"))
	if err != nil || len(files) == 0 {
		panic(fmt.Sprint("no catalogs in ", dir, err))
	}
	sort.Strings(files)
	keySet := map[string]bool{}
	langs := map[string]map[string]string{}
	var tags []string
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			panic(err)
		}
		m := map[string]string{}
		if err := json.Unmarshal(b, &m); err != nil {
			panic(fmt.Sprint(f, ": ", err))
		}
		tag := strings.TrimSuffix(filepath.Base(f), ".json")
		tags = append(tags, tag)
		langs[tag] = m
		for k := range m {
			if !strings.HasPrefix(k, "installer") {
				keySet[k] = true
			}
		}
	}
	var keys []string
	for k := range keySet {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_words.go from internal/l10n/messages. DO NOT EDIT.\n\n")
	b.WriteString("#include \"words.h\"\n\n")
	fmt.Fprintf(&b, "const char *const dsk_word_keys[DSK_WORD_KEYS] = {\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%s,\n", strconv.Quote(k))
	}
	b.WriteString("};\n\n")
	fmt.Fprintf(&b, "const dsk_word_lang dsk_word_langs[DSK_WORD_LANGS] = {\n")
	for _, t := range tags {
		fmt.Fprintf(&b, "\t{%s, {", strconv.Quote(t))
		for i, k := range keys {
			if i > 0 {
				b.WriteString(", ")
			}
			if v, ok := langs[t][k]; ok {
				b.WriteString(cQuote(v))
			} else {
				b.WriteString("0")
			}
		}
		b.WriteString("}},\n")
	}
	b.WriteString("};\n")
	h := fmt.Sprintf("// Code generated by gen_words.go. DO NOT EDIT.\n#ifndef DSK_WORDS_GEN_H\n#define DSK_WORDS_GEN_H\n\n#define DSK_WORD_KEYS %d\n#define DSK_WORD_LANGS %d\n\n#endif\n", len(keys), len(tags))
	if err := os.WriteFile(filepath.Join("src", "words_gen.h"), []byte(h), 0o644); err != nil {
		panic(err)
	}
	if err := os.WriteFile(filepath.Join("src", "words_gen.c"), b.Bytes(), 0o644); err != nil {
		panic(err)
	}
}

// cQuote is s as a C string literal of its UTF-8 (escaped bytes, so the
// source stays ASCII), split where a hex escape would run on.
func cQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	hex := false
	for i := 0; i < len(s); i++ {
		c := s[i]
		isHex := c >= '0' && c <= '9' || c >= 'a' && c <= 'f' || c >= 'A' && c <= 'F'
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
			hex = false
		case c < 0x20 || c >= 0x7f:
			fmt.Fprintf(&b, "\\x%02x", c)
			hex = true
			continue
		case hex && isHex:
			b.WriteString("\" \"")
			b.WriteByte(c)
		default:
			b.WriteByte(c)
		}
		hex = false
	}
	b.WriteByte('"')
	return b.String()
}
