// Command gen writes the prelude's elements.asuka and the C UI runtime's
// core/src/ui/elements_gen.h from lang/prelude's tables.
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/egoist/asuka/lang/prelude"
	"github.com/egoist/asuka/lang/syntax"
	"github.com/egoist/asuka/ops"
)

func main() {
	readEnums("types.asuka")
	write("elements.asuka", format("elements.asuka", asuka()))
	write("enums.asuka", format("enums.asuka", enums()))
	write(filepath.Join("..", "..", "core", "src", "ui", "elements_gen.h"), header())
}

func write(path string, b []byte) {
	if err := os.WriteFile(path, b, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// format is src as asuka fmt writes it.
func format(name string, src []byte) []byte {
	out, err := syntax.Format(name, src)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	return out
}

func upper(s string) string {
	var b strings.Builder
	for i, r := range s {
		if r >= 'A' && r <= 'Z' && i > 0 {
			b.WriteByte('_')
		}
		b.WriteString(strings.ToUpper(string(r)))
	}
	return b.String()
}

func doc(b *bytes.Buffer, indent, d string) {
	if d == "" {
		return
	}
	for _, l := range strings.Split(d, "\n") {
		fmt.Fprintf(b, "%s/// %s\n", indent, l)
	}
}

func asuka() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by lang/prelude/gen from lang/prelude/elements.go. DO NOT EDIT.\n\n")
	b.WriteString("/// The style every element takes (but fragments).\n")
	b.WriteString("native component Style {\n")
	for _, k := range prelude.Style {
		prop(&b, k)
	}
	b.WriteString("}\n")
	for _, e := range prelude.Elements {
		b.WriteString("\n")
		doc(&b, "", e.Doc)
		var params []string
		for _, k := range e.Keys {
			if k.Positional {
				p := k.Name + ": " + k.Type
				if k.Default != "" {
					p += " = " + k.Default
				}
				params = append(params, p)
			}
		}
		if e.Variants {
			fmt.Fprintf(&b, "///\n/// Takes the style's variants: %s { … }.\n", strings.Join(prelude.Variants, ", "))
		}
		fmt.Fprintf(&b, "native component %s(%s) {\n", e.Name, strings.Join(params, ", "))
		if e.Children {
			b.WriteString("  prop children: View? = none\n")
		}
		for _, k := range e.Keys {
			if !k.Positional {
				prop(&b, k)
			}
		}
		for _, ev := range e.Events {
			doc(&b, "  ", ev.Doc)
			var ps []string
			for _, p := range ev.Params {
				ps = append(ps, p.Name+": "+p.Type)
			}
			if len(ps) > 0 {
				fmt.Fprintf(&b, "  event %s(%s)\n", ev.Name, strings.Join(ps, ", "))
			} else {
				fmt.Fprintf(&b, "  event %s\n", ev.Name)
			}
		}
		for _, s := range e.Slots {
			doc(&b, "  ", s.Doc)
			fmt.Fprintf(&b, "  prop %s: View? = none\n", s.Name)
		}
		b.WriteString("}\n")
	}
	return b.Bytes()
}

// enums writes the wire's enums (ops/schema.go) as Asuka enums: a
// case's value is its wire value.
func enums() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by lang/prelude/gen from ops/schema.go. DO NOT EDIT.\n")
	for _, e := range ops.Schema.Enums {
		if skipEnum[e.Name] {
			continue
		}
		name := e.Name
		if r, ok := renameEnum[name]; ok {
			name = r
		}
		fmt.Fprintf(&b, "\nenum %s {\n", name)
		for _, v := range e.Values {
			fmt.Fprintf(&b, "  %s\n", lowerCamel(v))
		}
		b.WriteString("}\n")
		enumTypes[name] = true
	}
	return b.Bytes()
}

// The wire's enums that aren't the language's: what only the runtime
// encodes (canvas ops, paths, window actions) or hears (the error
// overlay's buttons), SemanticColor, whose cases are Color's, and
// Haptic, platform/device's.
var skipEnum = map[string]bool{"Haptic": true, "PathOp": true, "CanvasOp": true, "WindowAction": true, "LocationAction": true, "DevErrorAction": true, "VideoAction": true, "SemanticColor": true, "DetentKind": true}

var renameEnum = map[string]string{"Placement": "PopoverPlacement", "A11yChecked": "Checked", "A11yExpanded": "Expanded"}

func lowerCamel(s string) string {
	switch s {
	case "URL":
		return "url"
	case "None":
		return "off" // none is the language's empty optional
	}
	if s == "" {
		return s
	}
	// LeftToRight -> leftToRight; UltraThin -> ultraThin.
	return strings.ToLower(s[:1]) + s[1:]
}

func prop(b *bytes.Buffer, k prelude.Key) {
	doc(b, "  ", k.Doc)
	// A native component's prop with no default has its type's zero
	// value: false, 0, "", [], none, an enum's first case, a struct's
	// fields' zeros.
	if k.Default == "" {
		fmt.Fprintf(b, "  prop %s: %s\n", k.Name, k.Type)
		return
	}
	fmt.Fprintf(b, "  prop %s: %s = %s\n", k.Name, k.Type, k.Default)
}

// kind is how a key's value is stored (rt.h's ak_kind).
func kind(t string) string {
	switch t {
	case "bool":
		return "AK_K_BOOL"
	case "int", "Color", "Length", "Duration":
		return "AK_K_INT"
	case "float":
		return "AK_K_FLOAT"
	}
	if strings.HasSuffix(t, "?") || strings.HasPrefix(t, "[") || t == "string" || t == "View" {
		return "AK_K_REF"
	}
	// Prelude enums without payloads are ints; structs are references.
	if enumTypes[t] {
		return "AK_K_INT"
	}
	return "AK_K_REF"
}

// readEnums adds the payloadless enums a prelude file declares to
// enumTypes: their values are ints.
func readEnums(path string) {
	b, err := os.ReadFile(path)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	lines := strings.Split(string(b), "\n")
	for i, l := range lines {
		name, ok := strings.CutPrefix(l, "enum ")
		if !ok {
			continue
		}
		name = strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(name), "{"))
		payload := false
		for _, c := range lines[i+1:] {
			if strings.HasPrefix(c, "}") {
				break
			}
			payload = payload || strings.Contains(c, "(")
		}
		if !payload {
			enumTypes[name] = true
		}
	}
}

// enumTypes are types.asuka's payloadless enums (readEnums finds them).
var enumTypes = map[string]bool{
	"Axis": true, "Justify": true, "Align": true, "Platform": true, "SizeClass": true, "TextAlign": true, "Role": true, "Material": true,
	"ButtonVariant": true, "Keyboard": true, "TextStyle": true, "FontWeight": true, "RouteLayout": true,
}

func header() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by lang/prelude/gen from lang/prelude/elements.go. DO NOT EDIT.\n\n")
	b.WriteString("#ifndef AK_UI_ELEMENTS_GEN_H\n#define AK_UI_ELEMENTS_GEN_H\n\n#include \"rt/rt.h\"\n\n")
	b.WriteString("// Elements.\nenum {\n")
	for i, e := range prelude.Elements {
		fmt.Fprintf(&b, "\tAK_EL_%s = %d,\n", upper(e.Name), i+1)
	}
	fmt.Fprintf(&b, "\tAK_EL__COUNT = %d,\n};\n\n", len(prelude.Elements)+1)

	type key struct {
		c    string
		name string
		typ  string
		el   string
	}
	keys := []key{}
	for _, k := range prelude.Style {
		keys = append(keys, key{"AK_KEY_" + upper(k.Name), k.Name, k.Type, ""})
	}
	nstyle := len(keys)
	for _, e := range prelude.Elements {
		for _, k := range e.Keys {
			keys = append(keys, key{"AK_KEY_" + upper(e.Name) + "_" + upper(k.Name), k.Name, k.Type, e.Name})
		}
		for _, s := range e.Slots {
			keys = append(keys, key{"AK_KEY_" + upper(e.Name) + "_" + upper(s.Name), s.Name, "View?", e.Name})
		}
	}
	b.WriteString("// Keys: the style's (every element's) first, then each element's.\nenum {\n")
	for i, k := range keys {
		fmt.Fprintf(&b, "\t%s = %d, // %s: %s\n", k.c, i+1, k.name, k.typ)
		if i+1 == nstyle {
			fmt.Fprintf(&b, "\tAK_KEY__STYLE_END = %d,\n", nstyle+1)
		}
	}
	fmt.Fprintf(&b, "\tAK_KEY__COUNT = %d,\n};\n\n", len(keys)+1)

	b.WriteString("// Events.\nenum {\n")
	n := 0
	for _, e := range prelude.Elements {
		for _, ev := range e.Events {
			n++
			fmt.Fprintf(&b, "\tAK_EV_%s_%s = %d,\n", upper(e.Name), upper(ev.Name), n)
		}
	}
	fmt.Fprintf(&b, "\tAK_EV__COUNT = %d,\n};\n\n", n+1)

	b.WriteString("// Interaction states, which style variants follow (a bit each), in\n// the order variants are laid over the style.\nenum {\n")
	for i, v := range prelude.Variants {
		fmt.Fprintf(&b, "\tAK_STATE_%s = %d,\n", upper(v), 1<<i)
	}
	fmt.Fprintf(&b, "\tAK_STATE__COUNT = %d,\n};\n\n", len(prelude.Variants))

	b.WriteString("// The elements that take variants.\nstatic const bool ak_el_variants[] = {false,")
	for _, e := range prelude.Elements {
		fmt.Fprintf(&b, " %v,", e.Variants)
	}
	b.WriteString("};\n\n")

	b.WriteString("static const char *const ak_el_names[] = {\"\",")
	for _, e := range prelude.Elements {
		fmt.Fprintf(&b, " %q,", e.Name)
	}
	b.WriteString("};\n\nstatic const char *const ak_key_names[] = {\"\",")
	for _, k := range keys {
		fmt.Fprintf(&b, " %q,", k.name)
	}
	b.WriteString("};\n\n// How each key's value is stored.\nstatic const uint8_t ak_key_kinds[] = {0,")
	for _, k := range keys {
		fmt.Fprintf(&b, " %s,", kind(k.typ))
	}
	b.WriteString("};\n\n// The element each key is of (AK_EL_*); 0: the style's, every element's.\nstatic const uint8_t ak_key_els[] = {0,")
	elIndex := map[string]int{}
	for i, e := range prelude.Elements {
		elIndex[e.Name] = i + 1
	}
	for _, k := range keys {
		fmt.Fprintf(&b, " %d,", elIndex[k.el])
	}
	b.WriteString("};\n\nstatic const char *const ak_ev_names[] = {\"\",")
	for _, e := range prelude.Elements {
		for _, ev := range e.Events {
			fmt.Fprintf(&b, " %q,", e.Name+"."+ev.Name)
		}
	}
	b.WriteString("};\n\n// The element each event is of (AK_EL_*).\nstatic const uint8_t ak_ev_els[] = {0,")
	for i, e := range prelude.Elements {
		for range e.Events {
			fmt.Fprintf(&b, " %d,", i+1)
		}
	}
	b.WriteString("};\n\n#endif\n")
	return b.Bytes()
}
