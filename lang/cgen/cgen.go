// Package cgen compiles a module (lang/bytecode) to C, for release
// builds: each function becomes a C function that does what the VM's
// interpreter does for its instructions (both call the same bodies,
// core/src/vm/ops.h), on registers that are its C locals. A synchronous
// function is a plain C function. One that may suspend (async, or one
// that awaits) is resumable, as other languages compile coroutines: its
// frame is on the VM's coroutine, as an interpreted one's is, and its
// body enters through a switch on where the frame left; at an await
// that waits, or a call the VM's run loop goes on with, it moves its
// registers into the frame and returns, and the run loop resumes it
// (core/src/vm/interp.c). Async functions call each other directly in
// C while they don't wait. The module's data (constants, shapes,
// builtins' names) is embedded and loaded as the VM loads any module,
// then its functions get their compiled bodies (ak_module_attach), so
// compiled and interpreted code call each other freely.
//
// The C defines asuka_app_load, which the core's ABI calls in a release
// build instead of waiting for bytecode; for a program (a module with a
// fn main), a C main() too, which runs it (asuka_program_main): weak, so
// that a headless host that needs its own (platform/desktop's, the Mac's
// Swift for packages' Swift) replaces it.
package cgen

import (
	"bytes"
	"fmt"
	"math"
	"sort"
	"strings"

	bc "github.com/egoist/asuka/lang/bytecode"
)

// Generate compiles m to a C source file.
func Generate(m *bc.Module) ([]byte, error) { return GenerateMixed(m, nil) }

// GenerateMixed is Generate with the functions interpret says (by index)
// left to the VM: the tests' way to run compiled and interpreted
// functions calling each other.
func GenerateMixed(m *bc.Module, interpret func(i int) bool) ([]byte, error) {
	g := &gen{m: m}
	g.p("// Code generated by asuka build (lang/cgen). DO NOT EDIT.\n\n")
	g.p("#include \"vm/ops.h\"\n\n")
	g.p("static ak_module *M;\n")
	g.p("static AK_TLS int depth;\n\n")
	g.body = make([]body, len(m.Funcs))
	for i := range m.Funcs {
		g.body[i] = bodyOf(&m.Funcs[i])
		if interpret != nil && interpret(i) {
			g.body[i] = noBody
		}
		switch g.body[i] {
		case syncBody:
			g.p("static ak_val f%d(ak_val *A, ak_closure *C);\n", i)
		case asyncBody:
			g.p("static int f%d(ak_co *co, ak_val *out);\n", i)
		}
	}
	g.p("\n")
	for i := range m.Funcs {
		if g.body[i] == noBody {
			continue
		}
		if err := g.fn(i); err != nil {
			return nil, fmt.Errorf("cgen: %s: %v", m.Funcs[i].Name, err)
		}
	}
	table := func(decl string, b body) {
		g.p("%s = {", decl)
		for i := range max(len(m.Funcs), 1) {
			if i%8 == 0 {
				g.p("\n\t")
			} else {
				g.p(" ")
			}
			if i < len(m.Funcs) && g.body[i] == b {
				g.p("f%d,", i)
			} else {
				g.p("NULL,")
			}
		}
		g.p("\n};\n\n")
	}
	table(fmt.Sprintf("static ak_val (*const bodies[%d])(ak_val *, ak_closure *)", max(len(m.Funcs), 1)), syncBody)
	table(fmt.Sprintf("static int (*const resumes[%d])(ak_co *, ak_val *)", max(len(m.Funcs), 1)), asyncBody)
	data := m.Encode()
	g.p("static const uint8_t module_data[%d] = {", len(data))
	for i, b := range data {
		if i%20 == 0 {
			g.p("\n\t")
		}
		g.p("%d,", b)
	}
	g.p("\n};\n\n")
	g.p(`// asuka_app_load loads the app compiled into this build: its module,
// with its functions' compiled bodies. NULL (and a message on stderr) on
// failure.
static ak_module *asuka_app_load(void) {
	if (M) return M;
	char err[256];
	M = ak_module_load(module_data, sizeof module_data, err, sizeof err);
	if (!M) {
		ak_panic("the app's module doesn't load: %%s", err);
	}
	ak_module_attach(M, bodies, resumes, %d);
	return M;
}

// The core finds the app through ak_app_loader, set as the program
// starts; whether it reads its crash reports (platform/crash) through
// ak_app_crash, which asuka_crash_start asks before the app loads. A core
// built with the app (AK_APP_COMPILED) also names asuka_app_module, so
// that a static library's linker keeps this object.
extern bool ak_app_crash;
__attribute__((constructor)) static void register_app(void) {
	ak_app_loader = asuka_app_load;
	ak_app_crash = %t;
}
ak_module *asuka_app_module(void);
ak_module *asuka_app_module(void) { return asuka_app_load(); }
`, len(m.Funcs), readsCrashes(m))
	if m.Main >= 0 && m.Data != "" {
		g.p(`
// The folder the program's data goes in: the app's it ships with.
extern const char *ak_program_data;
__attribute__((constructor)) static void program_data(void) { ak_program_data = %s; }
`, cbytes(m.Data))
	}
	if m.Main >= 0 {
		g.p(`
// main runs the program (docs/programs.md): its arguments the system's
// (on Windows, read in UTF-16 by the core), its exit code main's.
#include "asuka.h"
int main(int argc, char **argv);
__attribute__((weak)) int main(int argc, char **argv) {
#if defined(_WIN32)
	AK_UNUSED(argc), AK_UNUSED(argv);
	return asuka_program_main(0, NULL, NULL);
#else
	return asuka_program_main(argc, argv, NULL);
#endif
}
`)
	}
	return g.b.Bytes(), nil
}

// readsCrashes reports whether m calls platform/crash's builtins: an app
// that reads its crash reports, whose runs the core records.
func readsCrashes(m *bc.Module) bool {
	for _, b := range m.Builtins {
		if strings.HasPrefix(b, "crash.") {
			return true
		}
	}
	return false
}

// body is what a function becomes.
type body int

const (
	noBody    body = iota // it stays on the VM (code cgen can't read)
	syncBody              // a C function: ak_native_body
	asyncBody             // a resumable one: ak_async_body
)

// bodyOf is what f becomes: a function that may suspend (async, or one
// that awaits or yields) is resumable.
func bodyOf(f *bc.FuncDef) body {
	b := syncBody
	if f.Flags&bc.FAsync != 0 {
		b = asyncBody
	}
	for pc := 0; pc < len(f.Code); {
		op := bc.Op(f.Code[pc])
		if int(op) >= len(bc.Ops) {
			return noBody
		}
		switch bc.Ops[op].Name {
		case "AWAIT", "YIELD":
			b = asyncBody
		}
		pc += op.Width()
	}
	return b
}

type gen struct {
	m     *bc.Module
	b     bytes.Buffer
	body  []body
	async bool // the function being written is resumable
}

func (g *gen) p(format string, args ...any) { fmt.Fprintf(&g.b, format, args...) }

type insn struct {
	pc   int
	op   bc.Op
	args []int // operands; an Off operand is the target pc
}

func decode(f *bc.FuncDef) ([]insn, map[int]bool, error) {
	var out []insn
	targets := map[int]bool{}
	for _, h := range f.Handlers {
		targets[int(h.Target)] = true
	}
	for pc := 0; pc < len(f.Code); {
		op := bc.Op(f.Code[pc])
		if int(op) >= len(bc.Ops) {
			return nil, nil, fmt.Errorf("bad opcode %d at %d", op, pc)
		}
		in := insn{pc: pc, op: op}
		at := pc + 1
		end := pc + op.Width()
		for _, o := range bc.Ops[op].Operands {
			if o == bc.Off {
				off := int32(uint32(f.Code[at]) | uint32(f.Code[at+1])<<16)
				t := end + int(off)
				in.args = append(in.args, t)
				targets[t] = true
				at += 2
				continue
			}
			in.args = append(in.args, int(f.Code[at]))
			at++
		}
		out = append(out, in)
		pc = end
	}
	return out, targets, nil
}

func (g *gen) fn(i int) error {
	f := &g.m.Funcs[i]
	ins, targets, err := decode(f)
	if err != nil {
		return err
	}
	g.async = g.body[i] == asyncBody
	n := len(f.Kinds)
	g.p("// %s (%s)\n", f.Name, f.File)
	g.p("static const uint8_t K%d[%d] = {", i, max(n, 1))
	for _, k := range f.Kinds {
		g.p("%d,", k)
	}
	g.p("};\n")
	g.p("#define K K%d\n#define N %d\n", i, n)
	var resume map[int]*insn
	if g.async {
		if resume, err = g.resumes(f, ins); err != nil {
			return err
		}
		// Its frame is the coroutine's top: its registers move into R,
		// and it goes on from where the frame left.
		g.p("static int f%d(ak_co *co, ak_val *out) {\n", i)
		g.p("\tconst uint32_t fi_ = co->nframes - 1;\n")
		g.p("\tak_closure *C = co->frames[fi_].clos; AK_UNUSED(C);\n")
		g.p("\tak_val R[%d];\n\tak_op_enter(co, fi_, R, N);\n\t++depth;\n", max(n, 1))
		g.p("\tuint32_t at_ = 0; AK_UNUSED(at_);\n")
		g.p("\tswitch (co->frames[fi_].pc) {\n")
		if _, ok := resume[0]; !ok {
			g.p("\tcase 0: break;\n")
		}
		pcs := make([]int, 0, len(resume))
		for pc := range resume {
			pcs = append(pcs, pc)
		}
		sort.Ints(pcs)
		for _, pc := range pcs {
			g.p("\tcase %d: goto S%d;\n", pc, pc)
		}
		g.p("\tdefault: ak_panic(\"vm: %s resumed at %%u\", co->frames[fi_].pc);\n\t}\n", cstr(f.Name))
	} else {
		g.p("static ak_val f%d(ak_val *A, ak_closure *C) {\n", i)
		g.p("\tAK_UNUSED(A); AK_UNUSED(C);\n")
		g.p("\tak_val R[%d];\n\tmemset(R, 0, sizeof R);\n", max(n, 1))
		g.p("\tif (AK_UNLIKELY(++depth > 10000)) { depth--; ak_throw_msg(\"stack overflow in %s\"); return (ak_val){0}; }\n", cstr(f.Name))
		for p := 0; p < int(f.NParams); p++ {
			if f.Kinds[p] == bc.KRef {
				g.p("\tR[%d].p = ak_retain(A[%d].p);\n", p, p)
			} else {
				g.p("\tR[%d] = A[%d];\n", p, p)
			}
		}
		// Where an error left from (its line), for a program's trace: set
		// on the error's path only.
		g.p("\tuint32_t at_ = 0; AK_UNUSED(at_);\n")
	}
	g.p("\tif (0) goto unwind;\n")
	for _, in := range ins {
		if r, ok := resume[in.pc]; ok {
			// Where the frame resumes; after a call the run loop went on
			// with, the call's error (it threw) goes to its handler.
			if r != nil {
				g.p("\tgoto T%d;\nS%d:\n", in.pc, in.pc)
				g.p("\tif (AK_UNLIKELY(ak_error_pending())) { at_ = %d; goto %s; }\n", lineAt(f, r.pc), handlerAt(f, r.pc))
				g.p("T%d:;\n", in.pc)
			} else {
				g.p("S%d:;\n", in.pc)
			}
		}
		if targets[in.pc] {
			// A handler's label may have no throwing instruction in its
			// range to jump to it: used either way.
			g.p("L%d:; if (0) goto L%d;\n", in.pc, in.pc)
		}
		if err := g.insn(f, in, handlerAt(f, in.pc)); err != nil {
			return err
		}
	}
	g.p("unwind:\n\tif (ak_frame_hook) ak_frame_hook(\"%s\", \"%s\", at_);\n", cstr(f.Name), cstr(f.File))
	if g.async {
		g.p("\tak_op_exit(R, K, N, -1);\n\tdepth--;\n\treturn AK_RUN_THROW;\n")
	} else {
		g.p("\tak_op_exit(R, K, N, -1);\n\tdepth--;\n\treturn (ak_val){0};\n")
	}
	g.p("#undef K\n#undef N\n}\n\n")
	return nil
}

// handlerAt is the label an error thrown at pc goes to: its innermost
// handler's, else unwind.
func handlerAt(f *bc.FuncDef, pc int) string {
	for _, hd := range f.Handlers {
		if pc >= int(hd.Start) && pc < int(hd.End) {
			return fmt.Sprintf("L%d", hd.Target)
		}
	}
	return "unwind"
}

// resumes are the pcs a resumable function's frame may resume at: an
// AWAIT's own (it runs again), and what follows a YIELD or a call that
// may push a frame. A call's is mapped to the call: the frame resumes
// there when the call returned or threw.
func (g *gen) resumes(f *bc.FuncDef, ins []insn) (map[int]*insn, error) {
	r := map[int]*insn{}
	for k := range ins {
		in := &ins[k]
		next := in.pc + in.op.Width()
		switch bc.Ops[in.op].Name {
		case "AWAIT":
			if _, ok := r[in.pc]; !ok {
				r[in.pc] = nil
			}
			continue
		case "YIELD":
		case "CALL":
			if g.body[in.args[1]] == syncBody {
				continue
			}
		case "CALLC", "CALLI":
		default:
			continue
		}
		if next >= len(f.Code) {
			return nil, fmt.Errorf("%s at %d is the last instruction", bc.Ops[in.op].Name, in.pc)
		}
		if bc.Ops[in.op].Name == "YIELD" {
			if _, ok := r[next]; !ok {
				r[next] = nil
			}
			continue
		}
		r[next] = in
	}
	return r, nil
}

// cbytes is s as a C string literal, byte by byte.
func cbytes(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c < 32 || c > 126 || c == '"' || c == '\\' || c == '?' {
			fmt.Fprintf(&b, "\\%03o", c)
		} else {
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func cstr(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case r == '"' || r == '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r < 32 || r > 126:
			fmt.Fprintf(&b, "\\x%02x", r&0xff)
		case r == '%':
			b.WriteString("%%")
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

func flit(v float64) string {
	switch {
	case math.IsNaN(v):
		return "NAN"
	case math.IsInf(v, 1):
		return "INFINITY"
	case math.IsInf(v, -1):
		return "(-INFINITY)"
	}
	return fmt.Sprintf("%#x", v) // hex float: exact
}

func ilit(v int64) string {
	if v == math.MinInt64 {
		return "INT64_MIN"
	}
	return fmt.Sprintf("INT64_C(%d)", v)
}

// store is C that puts the C expression v (an ak_val) in register a.
func store(f *bc.FuncDef, a int, v string, discardKind bc.Kind) string {
	if a == bc.None {
		if discardKind == bc.KRef {
			return fmt.Sprintf("ak_release((%s).p);", v)
		}
		return fmt.Sprintf("(void)(%s);", v)
	}
	if f.Kinds[a] == bc.KRef {
		return fmt.Sprintf("ak_op_setref(R, %d, (%s).p);", a, v)
	}
	return fmt.Sprintf("R[%d] = %s;", a, v)
}

// discard is C that puts the C expression v (an ak_val) in register a,
// or releases it, of the kind the C expression kind says, when a is
// None.
func discard(f *bc.FuncDef, a int, v, kind string) string {
	if a == bc.None {
		return fmt.Sprintf("ak_release_val(%s, (ak_kind)(%s));", v, kind)
	}
	return store(f, a, v, bc.KVoid)
}

// acall is C for a call (in) that pushes a frame on the coroutine, as
// the interpreter's does: fn (a C expression, the ak_func) with clos.
// The callee runs at once when it can (ak_op_acall); when it suspended,
// or the run loop is to run it, this frame leaves too, to resume after
// the call (resumes).
func (g *gen) acall(f *bc.FuncDef, in insn, h, fn, clos string) {
	a := in.args
	at := lineAt(f, in.pc)
	next := in.pc + in.op.Width()
	g.p("\t{ const ak_func *g_ = %s; ak_closure *cl_ = %s;\n", fn, clos)
	g.p("\t  if (!ak_vm_push(co, g_, cl_, &R[%d], %d, %d, false, %d)) { at_ = %d; goto %s; }\n", a[2], a[3], a[0], in.pc, at, h)
	g.p("\t  ak_val v_ = {0}; int s_ = ak_op_acall(co, &v_);\n")
	g.p("\t  if (s_ == AK_RUN_THROW) { at_ = %d; goto %s; }\n", at, h)
	g.p("\t  if (s_ != AK_RUN_RET) { ak_op_leave(co, fi_, R, N, %d); depth--; return s_; }\n", next)
	g.p("\t  %s }\n", discard(f, a[0], "v_", "g_->ret"))
}

// lineAt is the source line of f's code at pc.
func lineAt(f *bc.FuncDef, pc int) uint32 {
	var line uint32
	for _, l := range f.Lines {
		if int(l.PC) > pc {
			break
		}
		line = l.Line
	}
	return line
}

func (g *gen) insn(f *bc.FuncDef, in insn, h string) error {
	a := in.args
	at := lineAt(f, in.pc)
	thrown := fmt.Sprintf("if (AK_UNLIKELY(ak_error_pending())) { at_ = %d; goto %s; }", at, h)
	w := func(format string, args ...any) { g.p("\t"+format+"\n", args...) }
	switch name := bc.Ops[in.op].Name; name {
	case "NOP":
	case "MOV":
		w("R[%d] = R[%d];", a[0], a[1])
	case "MOVR":
		if a[0] != a[1] {
			w("ak_op_setref(R, %d, ak_retain(R[%d].p));", a[0], a[1])
		}
	case "CLR", "KNONE":
		w("ak_op_setref(R, %d, NULL);", a[0])
	case "KINT":
		w("R[%d].i = %s;", a[0], ilit(g.m.Ints[a[1]]))
	case "KSMALL":
		w("R[%d].i = %d;", a[0], int16(a[1]))
	case "KFLOAT":
		w("R[%d].f = %s;", a[0], flit(g.m.Floats[a[1]]))
	case "KSTR":
		w("ak_op_setref(R, %d, M->strings[%d]);", a[0], a[1])
	case "GGET":
		if bc.Kind(a[2]) == bc.KRef {
			w("ak_op_setref(R, %d, ak_retain(M->globals[%d].p));", a[0], a[1])
		} else {
			w("R[%d] = M->globals[%d];", a[0], a[1])
		}
	case "GSET":
		if bc.Kind(a[2]) == bc.KRef {
			w("{ void *o_ = M->globals[%d].p; M->globals[%d].p = ak_retain(R[%d].p); ak_release(o_); }", a[0], a[0], a[1])
		} else {
			w("M->globals[%d] = R[%d];", a[0], a[1])
		}
	case "ADDI", "SUBI", "MULI":
		op := map[string]string{"ADDI": "+", "SUBI": "-", "MULI": "*"}[name]
		w("R[%d].i = (int64_t)((uint64_t)R[%d].i %s (uint64_t)R[%d].i);", a[0], a[1], op, a[2])
	case "DIVI", "MODI":
		w("if (!ak_op_divi(R, %d, %d, %d, %v)) goto %s;", a[0], a[1], a[2], name == "MODI", h)
	case "NEGI":
		w("R[%d].i = (int64_t)(0 - (uint64_t)R[%d].i);", a[0], a[1])
	case "ADDIK":
		w("R[%d].i = (int64_t)((uint64_t)R[%d].i + (uint64_t)(int64_t)%d);", a[0], a[1], int16(a[2]))
	case "EQI", "NEI", "LTI", "LEI", "BAND", "BOR", "BXOR":
		op := map[string]string{"EQI": "==", "NEI": "!=", "LTI": "<", "LEI": "<=", "BAND": "&", "BOR": "|", "BXOR": "^"}[name]
		w("R[%d].i = R[%d].i %s R[%d].i;", a[0], a[1], op, a[2])
	case "BNOT":
		w("R[%d].i = ~R[%d].i;", a[0], a[1])
	case "SHL", "SHR":
		w("if (!ak_op_shift(R, %d, %d, %d, %v)) goto %s;", a[0], a[1], a[2], name == "SHR", h)
	case "ADDF", "SUBF", "MULF", "DIVF":
		op := map[string]string{"ADDF": "+", "SUBF": "-", "MULF": "*", "DIVF": "/"}[name]
		w("R[%d].f = R[%d].f %s R[%d].f;", a[0], a[1], op, a[2])
	case "MODF":
		w("R[%d].f = fmod(R[%d].f, R[%d].f);", a[0], a[1], a[2])
	case "NEGF":
		w("R[%d].f = -R[%d].f;", a[0], a[1])
	case "EQF", "NEF", "LTF", "LEF":
		op := map[string]string{"EQF": "==", "NEF": "!=", "LTF": "<", "LEF": "<="}[name]
		w("R[%d].i = R[%d].f %s R[%d].f;", a[0], a[1], op, a[2])
	case "I2F":
		w("R[%d].f = (double)R[%d].i;", a[0], a[1])
	case "F2I":
		w("R[%d].i = ak_op_f2i(R[%d].f);", a[0], a[1])
	case "NOT":
		w("R[%d].i = !R[%d].i;", a[0], a[1])
	case "EQ":
		w("R[%d].i = ak_val_eq(R[%d], R[%d], (ak_kind)%d);", a[0], a[1], a[2], a[3])
	case "NE":
		w("R[%d].i = !ak_val_eq(R[%d], R[%d], (ak_kind)%d);", a[0], a[1], a[2], a[3])
	case "ISNONE":
		w("R[%d].i = R[%d].p == NULL;", a[0], a[1])
	case "CONCAT":
		w("ak_op_setref(R, %d, ak_str_concat(R[%d].p, R[%d].p));", a[0], a[1], a[2])
	case "TOSTR":
		w("ak_op_setref(R, %d, ak_op_tostr(R[%d], %d));", a[0], a[1], a[2])
	case "INTERP":
		w("ak_op_setref(R, %d, ak_op_interp(R, %d, %d, M->strings[%d]));", a[0], a[1], a[2], a[3])
	case "LTS":
		w("R[%d].i = ak_str_cmp(R[%d].p, R[%d].p) < 0;", a[0], a[1], a[2])
	case "JMP":
		w("goto L%d;", a[0])
	case "JT":
		w("if (R[%d].i) goto L%d;", a[0], a[1])
	case "JF":
		w("if (!R[%d].i) goto L%d;", a[0], a[1])
	case "JNONE":
		w("if (!R[%d].p) goto L%d;", a[0], a[1])
	case "JSOME":
		w("if (R[%d].p) goto L%d;", a[0], a[1])
	case "CALL":
		callee := &g.m.Funcs[a[1]]
		if g.async && g.body[a[1]] != syncBody {
			// An async function (or one that may suspend) runs on this
			// coroutine, as the interpreter's CALL runs it.
			g.acall(f, in, h, fmt.Sprintf("&M->funcs[%d]", a[1]), "NULL")
			break
		}
		var call string
		if g.body[a[1]] == syncBody {
			call = fmt.Sprintf("f%d(&R[%d], NULL)", a[1], a[2])
		} else {
			call = fmt.Sprintf("ak_vm_call(&M->funcs[%d], &R[%d], %d)", a[1], a[2], a[3])
		}
		w("{ ak_val v_ = %s; %s %s }", call, thrown, store(f, a[0], "v_", callee.Ret))
	case "CALLC":
		if g.async {
			// A VM closure that may suspend runs on this coroutine; others
			// are called from C.
			w("{ ak_closure *c_ = R[%d].p; if (!c_) ak_panic(\"calling none\"); if (!ak_op_pushes(co, c_)) { ak_val v_ = c_->invoke(c_, &R[%d], %d); %s %s goto T%d; } }",
				a[1], a[2], a[3], thrown, store(f, a[0], "v_", bc.KVoid), in.pc+in.op.Width())
			g.acall(f, in, h, fmt.Sprintf("(const ak_func *)((ak_closure *)R[%d].p)->fn", a[1]), fmt.Sprintf("(ak_closure *)R[%d].p", a[1]))
			break
		}
		w("{ ak_closure *c_ = R[%d].p; if (!c_) ak_panic(\"calling none\"); ak_val v_ = c_->invoke(c_, &R[%d], %d); %s %s }", a[1], a[2], a[3], thrown, store(f, a[0], "v_", bc.KVoid))
	case "CALLB":
		w("{ ak_val v_ = M->builtins[%d](&R[%d], %d); %s %s }", a[1], a[2], a[3], thrown, store(f, a[0], "v_", bc.KVoid))
	case "CALLI":
		if g.async {
			// A method compiled to a C function is called from C; another
			// runs on this coroutine.
			w("{ const ak_func *g_ = ak_vm_method(R[%d].p, M->strings[%d]); if (!g_) ak_panic(\"no method %%s\", M->strings[%d]->data); if (g_->native) { ak_val v_ = g_->native(&R[%d], NULL); %s %s goto T%d; } }",
				a[2], a[1], a[1], a[2], thrown, discard(f, a[0], "v_", "g_->ret"), in.pc+in.op.Width())
			g.acall(f, in, h, fmt.Sprintf("ak_vm_method(R[%d].p, M->strings[%d])", a[2], a[1]), "NULL")
			break
		}
		w("{ const ak_func *g_ = ak_vm_method(R[%d].p, M->strings[%d]); if (!g_) ak_panic(\"no method %%s\", M->strings[%d]->data); ak_val v_ = g_->native ? g_->native(&R[%d], NULL) : ak_vm_call(g_, &R[%d], %d); %s %s }",
			a[2], a[1], a[1], a[2], a[2], a[3], thrown, store(f, a[0], "v_", bc.KRef))
	case "RET":
		keep := -1
		if f.Kinds[a[0]] == bc.KRef {
			keep = a[0]
		}
		if g.async {
			w("{ ak_val v_ = R[%d]; ak_op_exit(R, K, N, %d); depth--; *out = v_; return AK_RUN_RET; }", a[0], keep)
			break
		}
		w("{ ak_val v_ = R[%d]; ak_op_exit(R, K, N, %d); depth--; return v_; }", a[0], keep)
	case "RET0":
		if g.async {
			w("ak_op_exit(R, K, N, -1); depth--; *out = (ak_val){0}; return AK_RUN_RET;")
			break
		}
		w("ak_op_exit(R, K, N, -1); depth--; return (ak_val){0};")
	case "THROW":
		w("{ void *e_ = R[%d].p; R[%d].p = NULL; ak_throw(e_); at_ = %d; goto %s; }", a[0], a[0], at, h)
	case "CATCH":
		w("ak_op_setref(R, %d, ak_error_take());", a[0])
	case "RETHROW":
		w("{ void *e_ = R[%d].p; R[%d].p = NULL; ak_throw(e_); at_ = %d; goto unwind; }", a[0], a[0], at)
	case "CLOS":
		w("ak_op_setref(R, %d, ak_op_clos(&M->funcs[%d], &R[%d]));", a[0], a[1], a[2])
	case "CAP":
		w("ak_op_cap(R, %d, C, %d);", a[0], a[1])
	case "VBOX":
		w("ak_op_vbox(R, %d, R[%d], %d);", a[0], a[1], a[2])
	case "VGET":
		w("ak_op_vget(R, %d, R[%d].p);", a[0], a[1])
	case "VSET":
		w("ak_op_vset(R[%d].p, R[%d]);", a[0], a[1])
	case "NEWS":
		w("ak_op_setref(R, %d, ak_op_news(&M->shapes[%d].s, &R[%d]));", a[0], a[1], a[2])
	case "GETF":
		w("ak_op_getf(R, %d, R[%d].p, %d);", a[0], a[1], a[2])
	case "SETF":
		w("ak_op_setf(R, %d, %d, R[%d]);", a[0], a[1], a[2])
	case "NEWE":
		w("ak_op_setref(R, %d, ak_op_newe(&M->shapes[%d].s, %d, &R[%d]));", a[0], a[1], a[2], a[3])
	case "ECASE":
		w("R[%d].i = ak_enum_case(R[%d].p);", a[0], a[1])
	case "GETP":
		w("ak_op_getp(R, %d, R[%d].p, %d);", a[0], a[1], a[2])
	case "BOX":
		w("ak_op_setref(R, %d, ak_box_new((ak_kind)%d, R[%d]));", a[0], a[2], a[1])
	case "UNBOX":
		w("R[%d] = ((ak_box *)R[%d].p)->v;", a[0], a[1])
	case "NEWA":
		shape := "NULL"
		if a[2] != bc.None {
			shape = fmt.Sprintf("&M->shapes[%d].s", a[2])
		}
		w("ak_op_setref(R, %d, ak_op_newa((ak_kind)%d, %s, &R[%d], %d));", a[0], a[1], shape, a[3], a[4])
	case "IDX":
		w("if (!ak_op_idx(R, %d, R[%d].p, R[%d].i)) goto %s;", a[0], a[1], a[2], h)
	case "SETIDX":
		w("if (!ak_op_setidx(R, %d, R[%d].i, R[%d])) goto %s;", a[0], a[1], a[2], h)
	case "LEN":
		w("R[%d].i = ak_op_len(R[%d].p);", a[0], a[1])
	case "NEWM":
		w("ak_op_setref(R, %d, ak_op_newm((ak_kind)%d, (ak_kind)%d, &R[%d], %d));", a[0], a[1], a[2], a[3], a[4])
	case "MGET":
		w("ak_op_setref(R, %d, ak_op_mget(R[%d].p, R[%d]));", a[0], a[1], a[2])
	case "MSET":
		w("ak_op_mset(R, %d, R[%d], R[%d]);", a[0], a[1], a[2])
	case "CELL", "CELLK":
		key := "NULL"
		if name == "CELLK" {
			key = fmt.Sprintf("M->strings[%d]", a[3])
		}
		w("{ ak_val v_ = R[%d]; ak_retain_val(v_, (ak_kind)%d); ak_val c_ = ak_vm_cell_new(v_, (ak_kind)%d, %s); ak_op_setref(R, %d, c_.p); }", a[1], a[2], a[2], key, a[0])
	case "CGET", "CPEEK":
		w("{ ak_val v_ = ak_vm_cell_get(R[%d].p, %v); %s }", a[1], name == "CGET", store(f, a[0], "v_", bc.KVoid))
	case "CSET":
		w("{ ak_val v_ = R[%d]; ak_retain_val(v_, (ak_kind)K[%d]); ak_vm_cell_set(R[%d].p, v_); %s }", a[1], a[1], a[0], thrown)
	case "CTAKE":
		w("{ ak_val v_ = ak_vm_cell_take(R[%d].p); %s }", a[1], store(f, a[0], "v_", bc.KVoid))
	case "CPUT":
		w("{ ak_val v_ = R[%d]; if (K[%d] == AK_K_REF) R[%d].p = NULL; ak_vm_cell_put(R[%d].p, v_); %s }", a[1], a[1], a[1], a[0], thrown)
	case "MEMO":
		w("ak_op_setref(R, %d, ak_vm_memo_new(R[%d].p, (ak_kind)%d).p);", a[0], a[1], a[2])
	case "MREAD":
		w("{ ak_val v_ = ak_vm_memo_get(R[%d].p); %s %s }", a[1], thrown, store(f, a[0], "v_", bc.KVoid))
	case "ACCV":
		w("{ ak_val v_ = R[%d]; ak_retain_val(v_, (ak_kind)%d); ak_op_setref(R, %d, ak_vm_acc_value(v_, (ak_kind)%d).p); }", a[1], a[2], a[0], a[2])
	case "ACCF":
		w("ak_op_setref(R, %d, ak_vm_acc_func(R[%d].p, (ak_kind)%d).p);", a[0], a[1], a[2])
	case "ACCC":
		w("ak_op_setref(R, %d, ak_vm_acc_cell(R[%d].p).p);", a[0], a[1])
	case "AGET":
		w("{ ak_val v_ = ak_vm_acc_get(R[%d].p); %s %s }", a[1], thrown, store(f, a[0], "v_", bc.KVoid))
	case "UNTRACK":
		w("{ ak_val v_ = ak_vm_untrack(R[%d].p, &R[%d], %d); %s %s }", a[1], a[2], a[3], thrown, store(f, a[0], "v_", bc.KVoid))
	case "EFFECT", "RENDER":
		w("ak_vm_effect(R[%d].p, %v); %s", a[0], name == "RENDER", thrown)
	case "CLEANUP":
		w("ak_vm_cleanup(R[%d].p);", a[0])
	case "BATCH":
		w("ak_vm_batch(%v); %s", a[0] != 0, thrown)
	case "TASK":
		w("{ ak_val v_ = ak_op_task(R[%d].p); %s ak_op_setref(R, %d, v_.p); }", a[1], thrown, a[0])
	case "AWAIT":
		if !g.async {
			return fmt.Errorf("AWAIT in a function that can't suspend")
		}
		// Waiting: the frame keeps the registers and resumes here, at the
		// AWAIT, which runs again with the future settled.
		w("{ int w_ = ak_vm_await(co, R[%d].p); if (w_ < 0) { at_ = %d; goto %s; } if (w_ > 0) { ak_op_leave(co, fi_, R, N, %d); depth--; return AK_RUN_SUSPEND; } }", a[1], at, h, in.pc)
		w("{ ak_val v_ = ak_future_take(R[%d].p); %s %s }", a[1], thrown, store(f, a[0], "v_", bc.KVoid))
	case "YIELD":
		if !g.async {
			return fmt.Errorf("YIELD in a function that can't suspend")
		}
		w("ak_vm_yield(co); ak_op_leave(co, fi_, R, N, %d); depth--; return AK_RUN_SUSPEND;", in.pc+in.op.Width())
	default:
		return fmt.Errorf("no C for %s", name)
	}
	return nil
}
