// Package cgen compiles a module (lang/bytecode) to C, for release
// builds: each function becomes a C function that does what the VM's
// interpreter does for its instructions (both call the same bodies,
// core/src/vm/ops.h), on registers that are its C locals, one per
// register, so that the C compiler keeps them in machine registers.
//
// A synchronous function is two C functions: its body (fN_), which
// takes its arguments as C values of their kinds, the depth of the
// calls it's in and the thread's stack limit, and returns its result
// with whether it threw (ak_ret, in two machine registers); and the
// VM's entry to it (fN, an ak_native_body), which the interpreter,
// closures and builtins call. Compiled functions call each other's
// bodies directly, so a call costs what a C call does: no argument
// block in memory, no thread-local reads, and one test of a register
// for the error.
//
// One that may suspend (async, or one that awaits) is resumable, as
// other languages compile coroutines: its frame is on the VM's
// coroutine, as an interpreted one's is, and its body enters through a
// switch on where the frame left; at an await that waits, or a call the
// VM's run loop goes on with, it moves its registers into the frame and
// returns, and the run loop resumes it (core/src/vm/interp.c). Async
// functions call each other directly in C while they don't wait. The
// module's data (constants, shapes, builtins' names) is embedded and
// loaded as the VM loads any module, then its functions get their
// compiled bodies (ak_module_attach), so compiled and interpreted code
// call each other freely.
//
// The C defines asuka_app_load, which the core's ABI calls in a release
// build instead of waiting for bytecode; for a program (a module with a
// fn main), a C main() too, which runs it (asuka_program_main): weak, so
// that a headless host that needs its own (platform/desktop's, the Mac's
// Swift for packages' Swift) replaces it.
package cgen

import (
	"bytes"
	"fmt"
	"math"
	"sort"
	"strings"

	bc "github.com/egoist/asuka/lang/bytecode"
)

// Generate compiles m to a C source file.
func Generate(m *bc.Module) ([]byte, error) { return GenerateMixed(m, nil) }

// GenerateMixed is Generate with the functions interpret says (by index)
// left to the VM: the tests' way to run compiled and interpreted
// functions calling each other.
func GenerateMixed(m *bc.Module, interpret func(i int) bool) ([]byte, error) {
	g := &gen{m: m, stable: stableGlobals(m)}
	g.p("// Code generated by asuka build (lang/cgen). DO NOT EDIT.\n\n")
	g.p("#include \"vm/ops.h\"\n\n")
	g.p("static ak_module *M;\n\n")
	g.body = make([]body, len(m.Funcs))
	for i := range m.Funcs {
		g.body[i] = bodyOf(&m.Funcs[i])
		if interpret != nil && interpret(i) {
			g.body[i] = noBody
		}
	}
	for i := range m.Funcs {
		switch g.body[i] {
		case syncBody:
			g.p("%s;\n", g.direct(i))
			g.p("static ak_val f%d(ak_val *A, ak_closure *C);\n", i)
			g.p("static ak_ret f%d_c(ak_closure *C, uintptr_t lim_, ak_val *A);\n", i)
		case asyncBody:
			g.p("static int f%d(ak_co *co, ak_val *out);\n", i)
			g.p("static int f%d_a(ak_co *co, ak_val *out);\n", i)
		}
	}
	g.p("\n")
	for i := range m.Funcs {
		if g.body[i] == noBody {
			continue
		}
		if err := g.fn(i); err != nil {
			return nil, fmt.Errorf("cgen: %s: %v", m.Funcs[i].Name, err)
		}
	}
	table := func(decl string, b body, suffix string) {
		g.p("%s = {", decl)
		for i := range max(len(m.Funcs), 1) {
			if i%8 == 0 {
				g.p("\n\t")
			} else {
				g.p(" ")
			}
			if i < len(m.Funcs) && g.body[i] == b {
				g.p("f%d%s,", i, suffix)
			} else {
				g.p("NULL,")
			}
		}
		g.p("\n};\n\n")
	}
	table(fmt.Sprintf("static ak_val (*const bodies[%d])(ak_val *, ak_closure *)", max(len(m.Funcs), 1)), syncBody, "")
	table(fmt.Sprintf("static ak_ret (*const directs[%d])(ak_closure *, uintptr_t, ak_val *)", max(len(m.Funcs), 1)), syncBody, "_c")
	// The direct bodies, as a call through a closure finds them (ak_func's
	// body and sig).
	g.p("static void (*const direct_bodies[%d])(void) = {", max(len(m.Funcs), 1))
	for i := range max(len(m.Funcs), 1) {
		if i%8 == 0 {
			g.p("\n\t")
		} else {
			g.p(" ")
		}
		if i < len(m.Funcs) && g.body[i] == syncBody && int(m.Funcs[i].NParams) <= maxValueParams {
			g.p("(void (*)(void))f%d_,", i)
		} else {
			g.p("NULL,")
		}
	}
	g.p("\n};\n\n")
	table(fmt.Sprintf("static int (*const resumes[%d])(ak_co *, ak_val *)", max(len(m.Funcs), 1)), asyncBody, "")
	data := m.Encode()
	g.p("static const uint8_t module_data[%d] = {", len(data))
	for i, b := range data {
		if i%20 == 0 {
			g.p("\n\t")
		}
		g.p("%d,", b)
	}
	g.p("\n};\n\n")
	g.p(`// asuka_app_load loads the app compiled into this build: its module,
// with its functions' compiled bodies. NULL (and a message on stderr) on
// failure.
static ak_module *asuka_app_load(void) {
	if (M) return M;
	char err[256];
	M = ak_module_load(module_data, sizeof module_data, err, sizeof err);
	if (!M) {
		ak_panic("the app's module doesn't load: %%s", err);
	}
	ak_module_attach(M, bodies, directs, direct_bodies, resumes, %d);
	return M;
}

// The core finds the app through ak_app_loader, set as the program
// starts; whether it reads its crash reports (platform/crash) through
// ak_app_crash, which asuka_crash_start asks before the app loads. A core
// built with the app (AK_APP_COMPILED) also names asuka_app_module, so
// that a static library's linker keeps this object.
extern bool ak_app_crash;
__attribute__((constructor)) static void register_app(void) {
	ak_app_loader = asuka_app_load;
	ak_app_crash = %t;
}
ak_module *asuka_app_module(void);
ak_module *asuka_app_module(void) { return asuka_app_load(); }
`, len(m.Funcs), readsCrashes(m))
	if m.Main >= 0 && m.Data != "" {
		g.p(`
// The folder the program's data goes in: the app's it ships with.
extern const char *ak_program_data;
__attribute__((constructor)) static void program_data(void) { ak_program_data = %s; }
`, cbytes(m.Data))
	}
	if m.Main >= 0 {
		g.p(`
// main runs the program (docs/programs.md): its arguments the system's
// (on Windows, read in UTF-16 by the core), its exit code main's.
#include "asuka.h"
int main(int argc, char **argv);
__attribute__((weak)) int main(int argc, char **argv) {
#if defined(_WIN32)
	AK_UNUSED(argc), AK_UNUSED(argv);
	return asuka_program_main(0, NULL, NULL);
#else
	return asuka_program_main(argc, argv, NULL);
#endif
}
`)
	}
	return g.b.Bytes(), nil
}

// readsCrashes reports whether m calls platform/crash's builtins: an app
// that reads its crash reports, whose runs the core records.
func readsCrashes(m *bc.Module) bool {
	for _, b := range m.Builtins {
		if strings.HasPrefix(b, "crash.") {
			return true
		}
	}
	return false
}

// body is what a function becomes.
type body int

const (
	noBody    body = iota // it stays on the VM (code cgen can't read)
	syncBody              // a C function: ak_native_body, and its direct body
	asyncBody             // a resumable one: ak_async_body
)

// bodyOf is what f becomes: a function that may suspend (async, or one
// that awaits or yields) is resumable.
func bodyOf(f *bc.FuncDef) body {
	b := syncBody
	if f.Flags&bc.FAsync != 0 {
		b = asyncBody
	}
	for pc := 0; pc < len(f.Code); {
		op := bc.Op(f.Code[pc])
		if int(op) >= len(bc.Ops) {
			return noBody
		}
		switch bc.Ops[op].Name {
		case "AWAIT", "YIELD":
			b = asyncBody
		}
		pc += op.Width()
	}
	return b
}

// maxLocals is how many registers a function's C has as locals of their
// own; one with more has them as an array. Compilers' register
// allocation and their sanitizers' instrumentation of locals grow faster
// than linearly with them: a function of thousands (a big module's
// init) would take minutes to compile.
var maxLocals = 384

// maxValueParams is how many parameters a direct body takes as C
// values; one with more takes them as an array, as the VM's entry does.
const maxValueParams = 16

type gen struct {
	m    *bc.Module
	b    bytes.Buffer
	body []body

	// The function being written.
	f        *bc.FuncDef
	fi       int
	async    bool
	out      bytes.Buffer // its body's code
	used     []bool       // its registers the code names
	jumped   map[int]bool // the labels code jumps to
	borrowed []bool       // its parameters it borrows: never retained, never released
	unwinds  bool         // the code goes to unwind_
	low      bool         // it checks the stack (low_)
	// array: its registers are an array (R), not locals: a function with
	// more than maxLocals of them (a module's init, a large view), which
	// a C compiler takes too long to keep in machine registers.
	array bool
	pl    *plan // its places (places.go)
	// maybe: before each instruction, the reference registers that may
	// hold one (live.go), for its returns; nil: they go through out_.
	maybe []regset
	k     int  // the instruction being written, by index
	tramp bool // the instruction's code goes to its trampoline (inlined)
	// stable: the module's globals only its init writes (stableGlobals).
	stable []bool
	// stack: the INTERPs and CONCATs whose string is made in the frame
	// (S<k>_) when it fits; stackCopy: the MOVRs that may copy one
	// (stackstr.go).
	stack, stackCopy map[int]bool
	// The fused loops' write cursors (cursor.go): the cursors, the
	// appends' CALLBs that write through one (by index), the ways out of
	// their loops' code, and the instructions' indexes by pc.
	curs     []*cursor
	curDance map[int]*cursor
	stubs    []stub
	at       map[int]int
}

// stableGlobals reports, by index, the module's globals that no function
// but its init writes (GSET, GTAKE): a file's let, set once as the
// module starts. Elsewhere one's value never changes, so a read of it
// may be borrowed (places.go) whatever runs on the way.
func stableGlobals(m *bc.Module) []bool {
	stable := make([]bool, len(m.Globals))
	for i := range stable {
		stable[i] = true
	}
	for i := range m.Funcs {
		if uint32(i) == m.Init {
			continue
		}
		ins, _, err := decode(&m.Funcs[i])
		if err != nil {
			return make([]bool, len(m.Globals))
		}
		for _, in := range ins {
			g := -1
			switch bc.Ops[in.op].Name {
			case "GSET":
				g = in.args[0]
			case "GTAKE":
				g = in.args[1]
			}
			if g >= 0 && g < len(stable) {
				stable[g] = false
			}
		}
	}
	return stable
}

func (g *gen) p(format string, args ...any) { fmt.Fprintf(&g.b, format, args...) }

// w writes a line of the function's code.
func (g *gen) w(format string, args ...any) {
	g.out.WriteByte('\t')
	fmt.Fprintf(&g.out, format, args...)
	g.out.WriteByte('\n')
}

// r is register i as a C lvalue (an ak_val): a local of its own, or in
// a function with too many to be the C compiler's locals, an element of
// the array R.
func (g *gen) r(i int) string {
	g.used[i] = true
	if g.array {
		return fmt.Sprintf("R[%d]", i)
	}
	return fmt.Sprintf("r%d", i)
}

// member is the ak_val member a value of kind k is in.
func member(k bc.Kind) string {
	switch k {
	case bc.KFloat:
		return "f"
	case bc.KRef:
		return "p"
	}
	return "i"
}

// ctype is the C type a value of kind k is passed as.
func ctype(k bc.Kind) string {
	switch k {
	case bc.KFloat:
		return "double "
	case bc.KRef:
		return "void *"
	}
	return "int64_t "
}

func (g *gen) ri(i int) string { return g.r(i) + ".i" }
func (g *gen) rf(i int) string { return g.r(i) + ".f" }
func (g *gen) rp(i int) string { return g.r(i) + ".p" }

// rk is register i's value as its kind's C type.
func (g *gen) rk(i int) string { return g.r(i) + "." + member(g.f.Kinds[i]) }

func (g *gen) isRef(i int) bool { return i != bc.None && g.f.Kinds[i] == bc.KRef }

// label is the C label of the instruction at pc, noted as jumped to.
func (g *gen) label(pc int) string {
	g.jumped[pc] = true
	l := fmt.Sprintf("L%d", pc)
	if t, ok := g.at[pc]; ok && len(g.curs) > 0 {
		if cs := g.leaving(t); len(cs) > 0 {
			// Out of loops with write cursors: through code closing them.
			return g.stubTo(cs, "goto "+l+";")
		}
	}
	return l
}

// to is a jump to h (handlerAt's: a label, or "unwind"; inlined's: an
// inlined body's trampoline, noted as used).
func (g *gen) to(h string) string {
	if h == "unwind" {
		g.unwinds = true
		if cs := g.leaving(-1); len(cs) > 0 {
			return "goto " + g.stubTo(cs, "goto unwind_;") + ";"
		}
		return "goto unwind_;"
	}
	if strings.HasPrefix(h, "I") {
		g.tramp = true
		return "goto " + h + ";"
	}
	var pc int
	fmt.Sscanf(h, "L%d", &pc)
	return "goto " + g.label(pc) + ";"
}

// setref is C that puts the reference v (a C expression, owned) in
// register a, releasing what it held after v is computed.
func (g *gen) setref(a int, v string) string {
	r := g.rp(a)
	return fmt.Sprintf("{ void *n_ = (%s); void *o_ = %s; %s = n_; ak_release(o_); }", v, r, r)
}

// put is C that puts v (a C expression, an ak_val of kind k, owned) in
// register a, or releases it when a is None.
func (g *gen) put(a int, v string, k bc.Kind) string {
	if a == bc.None {
		if k == bc.KRef {
			return fmt.Sprintf("ak_release((%s).p);", v)
		}
		return fmt.Sprintf("(void)(%s);", v)
	}
	if g.isRef(a) {
		return g.setref(a, "("+v+").p")
	}
	return fmt.Sprintf("%s = %s;", g.r(a), v)
}

// load is C that puts v (an ak_val of register a's kind, borrowed) in
// register a: retained when it's a reference.
func (g *gen) load(a int, v string) string {
	if g.isRef(a) {
		return g.setref(a, fmt.Sprintf("ak_retain((%s).p)", v))
	}
	return fmt.Sprintf("%s = %s;", g.r(a), v)
}

// block is C declaring B_, a copy of the n registers from b: an argument
// block for code that takes one (a builtin, the VM, a closure), so that
// the registers themselves never have their address taken.
func (g *gen) block(b, n int) string {
	if n <= 0 || b == bc.None {
		return "ak_val *B_ = NULL;"
	}
	if g.array {
		g.used[b] = true
		return fmt.Sprintf("ak_val *B_ = &R[%d];", b)
	}
	n = min(n, len(g.f.Kinds)-b)
	parts := make([]string, n)
	for i := range parts {
		parts[i] = g.r(b + i)
	}
	return fmt.Sprintf("ak_val B_[%d] = {%s};", n, strings.Join(parts, ", "))
}

// back is C that copies the argument block B_ back into its registers:
// what the callee changed in place (an inout builtin's receiver, a mut
// fn's).
func (g *gen) back(b, n int) string {
	if n <= 0 || b == bc.None || g.array {
		return ""
	}
	n = min(n, len(g.f.Kinds)-b)
	var s strings.Builder
	for i := range n {
		fmt.Fprintf(&s, "%s = B_[%d]; ", g.r(b+i), i)
	}
	return s.String()
}

type insn struct {
	pc   int
	op   bc.Op
	args []int // operands; an Off operand is the target pc
}

func decode(f *bc.FuncDef) ([]insn, map[int]bool, error) {
	var out []insn
	targets := map[int]bool{}
	for _, h := range f.Handlers {
		targets[int(h.Target)] = true
	}
	for pc := 0; pc < len(f.Code); {
		op := bc.Op(f.Code[pc])
		if int(op) >= len(bc.Ops) {
			return nil, nil, fmt.Errorf("bad opcode %d at %d", op, pc)
		}
		in := insn{pc: pc, op: op}
		at := pc + 1
		end := pc + op.Width()
		for _, o := range bc.Ops[op].Operands {
			switch {
			case o == bc.Off:
				t := end + int(int32(bc.Word32(f.Code, at)))
				in.args = append(in.args, t)
				targets[t] = true
			case o.Words() == 2:
				// An index; NEWA's NoShape is -1.
				in.args = append(in.args, int(int32(bc.Word32(f.Code, at))))
			default:
				in.args = append(in.args, int(f.Code[at]))
			}
			at += o.Words()
		}
		out = append(out, in)
		pc = end
	}
	return out, targets, nil
}

// direct is the declaration of function i's direct body: its parameters
// as C values (a mut fn's receiver by its address), or an array of them
// past maxValueParams, then its closure (NULL for a CALL) and the
// thread's stack limit (ops.h's AK_CG_LIM_P: none on arm64). The
// parameters first: the first is in the register the result goes back
// in, and the second's isn't the one the error flag does (ak_ret's e), so
// a function returning what it's given (a recursion's base case) moves
// nothing.
func (g *gen) direct(i int) string {
	f := &g.m.Funcs[i]
	var b strings.Builder
	fmt.Fprintf(&b, "static ak_ret f%d_(", i)
	if int(f.NParams) > maxValueParams {
		b.WriteString("ak_val *A, ")
	} else {
		for p := 0; p < int(f.NParams); p++ {
			if p == 0 && f.Flags&bc.FMut != 0 {
				b.WriteString("ak_val *self_, ")
				continue
			}
			fmt.Fprintf(&b, "%sp%d, ", ctype(f.Kinds[p]), p)
		}
	}
	b.WriteString("ak_closure *C AK_CG_LIM_P)")
	return b.String()
}

// directArgs is the C arguments of a direct call of function i with its
// n arguments from register b, each followed by ", " (the closure and the
// limit come after them): self is the C lvalue a mut fn's receiver is
// moved through.
func (g *gen) directArgs(i, b, n int, self string) string {
	f := &g.m.Funcs[i]
	var s strings.Builder
	if int(f.NParams) > maxValueParams {
		return "B_, "
	}
	for p := 0; p < n; p++ {
		if p == 0 && f.Flags&bc.FMut != 0 {
			fmt.Fprintf(&s, "&%s, ", self)
			continue
		}
		fmt.Fprintf(&s, "%s, ", g.r(b+p)+"."+member(f.Kinds[p]))
	}
	return s.String()
}

func (g *gen) fn(i int) error {
	f := &g.m.Funcs[i]
	ins, targets, err := decode(f)
	if err != nil {
		return err
	}
	g.f, g.fi = f, i
	g.async = g.body[i] == asyncBody
	if g.async && f.Flags&bc.FMut != 0 {
		return fmt.Errorf("a mut fn that may suspend")
	}
	n := len(f.Kinds)
	g.out.Reset()
	g.used = make([]bool, n)
	g.jumped = map[int]bool{}
	g.unwinds = false
	g.low = false
	g.array = n > maxLocals
	g.borrowed = make([]bool, n)
	if !g.async && !g.array {
		g.borrowed = borrowedParams(g.m, f, ins)
	}
	var resume map[int]*insn
	if g.async {
		if resume, err = g.resumes(f, ins); err != nil {
			return err
		}
	}
	entries := map[int]bool{}
	for _, h := range f.Handlers {
		entries[int(h.Target)] = true
	}
	for pc := range resume {
		entries[pc] = true
	}
	var stable []bool
	if uint32(i) != g.m.Init {
		stable = g.stable
	}
	g.pl = analyze(g.m, f, ins, entries, stable)
	g.maybe = nil
	if !g.async && !g.array && f.Flags&bc.FMut == 0 && untracksIn(ins) == 0 {
		g.maybe = g.maybeRefs(ins)
	}
	g.stack, g.stackCopy = g.stackStrs(ins)
	g.cursors(ins, targets)
	untracks := 0
	for _, in := range ins {
		if bc.Ops[in.op].Name == "UNTRACK" {
			untracks++
		}
	}
	for k, in := range ins {
		g.k = k
		if h := g.pl.hoists[k]; h != nil {
			// Falling into a loop (flow.go): what it changes made unique
			// once, here, not a turn.
			g.hoistC(h)
		}
		// Falling into a loop that appends through a cursor: it's opened.
		g.curOpen(k)
		if r, ok := resume[in.pc]; ok {
			// Where the frame resumes; after a call the run loop went on
			// with, the call's error (it threw) goes to its handler.
			if r != nil {
				g.w("goto T%d;", in.pc)
				g.out.WriteString(fmt.Sprintf("S%d:\n", in.pc))
				g.w("if (AK_UNLIKELY(ak_cg_pending(&E_))) { at_ = %d; %s }", lineAt(f, r.pc), g.to(handlerAt(f, r.pc)))
				g.out.WriteString(fmt.Sprintf("T%d:;\n", in.pc))
			} else {
				g.out.WriteString(fmt.Sprintf("S%d:;\n", in.pc))
			}
		}
		if targets[in.pc] {
			g.out.WriteString(fmt.Sprintf("@L%d@", in.pc))
		}
		if g.pl.skip[k] {
			continue
		}
		h, tramp := g.inlined(f, in.pc, handlerAt(f, in.pc))
		g.tramp = false
		if err := g.insn(f, in, h); err != nil {
			return err
		}
		if g.tramp {
			tramp()
		}
		// Falling out of a loop's end: its cursors closed.
		g.curLast(k, in)
	}
	// What falls off the end (code after a return the lowering left).
	g.w("goto out_;")
	// The ways out of cursors' loops (cursor.go).
	g.stubsC()
	code := g.out.String()
	// Labels nobody jumps to are left out (-Wunused-label).
	for pc := range targets {
		mark := fmt.Sprintf("@L%d@", pc)
		if g.jumped[pc] {
			code = strings.Replace(code, mark, fmt.Sprintf("L%d:;\n", pc), 1)
		} else {
			code = strings.Replace(code, mark, "", 1)
		}
	}
	// The registers, as locals: what the code names, and every reference
	// (released at the end); a reference starts as none.
	for r := range n {
		if f.Kinds[r] == bc.KRef || r < int(f.NParams) {
			g.used[r] = true
		}
	}
	g.p("// %s (%s)\n", f.Name, f.File)
	if g.array {
		g.p("static const uint8_t K%d[%d] = {", i, n)
		for _, k := range f.Kinds {
			g.p("%d,", k)
		}
		g.p("};\n")
	}
	if g.async {
		// Its body (fN_a), and its way in (fN, after it): the
		// thread's stack limit set (ops.h's AK_CG_ENTER).
		g.p("static int f%d_a(ak_co *co, ak_val *out) {\n", i)
		g.p("\tconst uint32_t fi_ = co->nframes - 1;\n")
		g.p("\tak_closure *C = co->frames[fi_].clos; AK_UNUSED(C);\n")
		g.p("\tAK_CG_ENTER(ak_op_lim(co)); AK_CG_LEAVE();\n")
		g.decls()
		// Its frame is the coroutine's top: its registers move into the
		// locals (the frame's left empty: nothing else releases them),
		// and it goes on from where the frame left.
		g.p("\t{ ak_val *S_ = co->regs + co->frames[fi_].base; AK_UNUSED(S_);\n\t  ")
		if g.array {
			g.p("memcpy(R, S_, sizeof R); ")
		} else {
			for r := range n {
				if g.used[r] {
					g.p("r%d = S_[%d]; ", r, r)
				}
			}
		}
		if n > 0 {
			g.p("memset(S_, 0, sizeof(ak_val) * %d);", n)
		}
		g.p(" }\n")
		g.p("\tuint32_t at_ = 0; AK_UNUSED(at_);\n")
		g.p("\tvoid *const *E_ = NULL; AK_UNUSED(E_);\n")
		g.p("\tswitch (co->frames[fi_].pc) {\n")
		if _, ok := resume[0]; !ok {
			g.p("\tcase 0: break;\n")
		}
		pcs := make([]int, 0, len(resume))
		for pc := range resume {
			pcs = append(pcs, pc)
		}
		sort.Ints(pcs)
		for _, pc := range pcs {
			g.p("\tcase %d: goto S%d;\n", pc, pc)
		}
		g.p("\tdefault: ak_panic(\"vm: %%s resumed at %%u\", %s, co->frames[fi_].pc);\n\t}\n", cbytes(f.Name))
	} else {
		g.p("%s {\n", g.direct(i))
		g.p("\tAK_UNUSED(C);\n")
		g.decls()
		// No deeper than the thread's C stack: a compare of the stack
		// pointer, before the frame is made. A function that calls
		// nothing can't recurse, and its frame fits in what the limit
		// leaves (base/stack.c's margin): it needn't check.
		if calls(ins) {
			g.p("\tAK_CG_CHECK(low_);\n")
			g.low = true
		}
		for p := 0; p < int(f.NParams); p++ {
			var v string
			switch {
			case int(f.NParams) > maxValueParams:
				v = fmt.Sprintf("A[%d].%s", p, member(f.Kinds[p]))
				if p == 0 && f.Flags&bc.FMut != 0 {
					// A mut fn's receiver moves in, and back as the
					// function ends (out_).
					g.p("\t%s = A[0]; A[0].p = NULL;\n", g.r(0))
					continue
				}
			case p == 0 && f.Flags&bc.FMut != 0:
				if f.Kinds[0] == bc.KRef {
					g.p("\t%s = *self_; self_->p = NULL;\n", g.r(0))
				} else {
					g.p("\t%s = *self_;\n", g.r(0))
				}
				continue
			default:
				v = fmt.Sprintf("p%d", p)
			}
			if f.Kinds[p] == bc.KRef && !g.borrowed[p] {
				g.p("\t%s.p = ak_retain(%s);\n", g.r(p), v)
			} else {
				g.p("\t%s.%s = %s;\n", g.r(p), member(f.Kinds[p]), v)
			}
		}
		// Where an error left from (its line), for a program's trace: set
		// on the error's path only.
		g.p("\tuint32_t at_ = 0; AK_UNUSED(at_);\n")
		g.p("\tvoid *const *E_ = NULL; AK_UNUSED(E_);\n")
		g.p("\tak_val ret_ = {0}; uintptr_t e_ = 0;\n")
	}
	if untracks > 0 && !g.async {
		// What its peeks untracked, ended as an error leaves (unwind).
		g.p("\tvoid *U_[%d] = {0}; uint32_t un_ = 0;\n", untracks) // zeroed: GCC can't see un_ counts what's set
	}
	g.b.WriteString(code)
	if g.low {
		// Past the stack's limit, as the body starts: nothing's held yet.
		g.p("low_:\n\treturn ak_cg_overflow(%s);\n", cbytes(f.Name))
	}
	if g.unwinds {
		g.p("unwind_:\n\tak_cg_unwind(%s, %s, at_);\n", cbytes(f.Name), cbytes(f.File))
		if untracks > 0 {
			// Out of a peek the error left: what it untracked tracks again.
			if g.async {
				g.p("\tak_vm_retrack(co, co->frames[fi_].udepth);\n")
			} else {
				g.p("\twhile (un_) ak_untrack_end(U_[--un_]);\n")
			}
		}
	}
	if g.async {
		if g.unwinds {
			g.p("%s", g.releases(-1))
			g.p("\treturn AK_RUN_THROW;\n")
		}
		g.p("out_:\n%s", g.releases(-1))
		g.p("\t*out = (ak_val){0};\n\treturn AK_RUN_RET;\n")
	} else {
		if g.unwinds {
			g.p("\te_ = 1;\n")
		}
		g.p("out_:\n")
		if f.Flags&bc.FMut != 0 && f.NParams > 0 {
			// The receiver goes back to the caller.
			self := "*self_"
			if int(f.NParams) > maxValueParams {
				self = "A[0]"
			}
			if f.Kinds[0] == bc.KRef {
				g.p("\t%s = r0; r0.p = NULL;\n", self)
			} else {
				g.p("\t%s = r0;\n", self)
			}
		}
		g.p("%s", g.releases(-1))
		g.p("\treturn (ak_ret){ret_, e_};\n")
	}
	g.p("}\n\n")
	if !g.async {
		g.entry(i)
	} else {
		g.p("static int f%d(ak_co *co, ak_val *out) { AK_CG_ENTER(ak_op_lim(co)); int s_ = f%d_a(co, out); AK_CG_LEAVE(); return s_; }\n\n", i, i)
	}
	return nil
}

// entry writes function i's entries with its arguments in A: as a
// closure compiled code calls (fN_c, an ak_direct_body: its direct body
// called with them), and the VM's (fN, an ak_native_body: that with the
// thread's stack limit).
func (g *gen) entry(i int) {
	f := &g.m.Funcs[i]
	g.p("static ak_ret f%d_c(ak_closure *C, uintptr_t lim, ak_val *A) {\n", i)
	g.p("\tAK_UNUSED(A);\n")
	g.p("\tAK_CG_ENTER(lim);\n")
	g.p("\tak_ret r_ = f%d_(", i)
	if int(f.NParams) > maxValueParams {
		g.p("A, ")
	} else {
		for p := 0; p < int(f.NParams); p++ {
			if p == 0 && f.Flags&bc.FMut != 0 {
				g.p("&A[0], ")
				continue
			}
			g.p("A[%d].%s, ", p, member(f.Kinds[p]))
		}
	}
	g.p("C AK_CG_LIM_A);\n\tAK_CG_LEAVE();\n\treturn r_;\n}\n\n")
	g.p("static ak_val f%d(ak_val *A, ak_closure *C) { return f%d_c(C, ak_stack_limit(), A).v; }\n\n", i, i)
}

// untracksIn counts ins' UNTRACKs (a function's peeks).
func untracksIn(ins []insn) int {
	n := 0
	for _, in := range ins {
		if bc.Ops[in.op].Name == "UNTRACK" {
			n++
		}
	}
	return n
}

// calls reports whether code calls anything: a function, a closure, a
// builtin or a method (what may come back to it).
func calls(ins []insn) bool {
	for _, in := range ins {
		switch bc.Ops[in.op].Name {
		case "CALL", "CALLB", "CALLC", "CALLU", "CALLI":
			return true
		}
	}
	return false
}

// decls declares the function's registers that its code names.
func (g *gen) decls() {
	if g.array {
		g.p("\tak_val R[%d];\n\tmemset(R, 0, sizeof R);\n", len(g.f.Kinds))
		g.virtDecls()
		return
	}
	var names []string
	for r, u := range g.used {
		if u {
			names = append(names, fmt.Sprintf("r%d = {0}", r))
		}
	}
	for k := 0; k < len(names); k += 16 {
		e := min(k+16, len(names))
		g.p("\tak_val %s;\n", strings.Join(names[k:e], ", "))
	}
	g.virtDecls()
	var unused []string
	for r, u := range g.used {
		if u {
			unused = append(unused, fmt.Sprintf("(void)r%d;", r))
		}
	}
	for k := 0; k < len(unused); k += 16 {
		g.p("\t%s\n", strings.Join(unused[k:min(k+16, len(unused))], " "))
	}
}

// virtDecls declares the pointers borrowed in place of registers
// (places.go): v<r>, register r's.
func (g *gen) virtDecls() {
	var rs []int
	for r := range g.pl.virt {
		rs = append(rs, r)
	}
	sort.Ints(rs)
	for _, r := range rs {
		g.p("\tvoid *v%d = NULL; (void)v%d;\n", r, r)
	}
	g.curDecls()
	// The strings made in the frame (stackstr.go).
	var ks []int
	for k := range g.stack {
		ks = append(ks, k)
	}
	sort.Ints(ks)
	for _, k := range ks {
		g.p("\tak_strbuf S%d_;\n", k)
	}
}

// src is register i read as a reference: the pointer borrowed in its
// place where it is borrowed (places.go).
func (g *gen) src(i int) string {
	for _, r := range g.pl.active[g.k] {
		if r == i {
			return fmt.Sprintf("v%d", i)
		}
	}
	return g.rp(i)
}

// releases is C releasing the function's reference registers but keep
// (-1: none) and those it borrows.
func (g *gen) releases(keep int) string {
	var s strings.Builder
	if g.array {
		// Every reference register but keep, as the kinds say.
		fmt.Fprintf(&s, "\tfor (uint32_t i_ = 0; i_ < %d; i_++) if (K%d[i_] == AK_K_REF && (int)i_ != %d) ak_release(R[i_].p);\n", len(g.f.Kinds), g.fi, keep)
		return s.String()
	}
	for r, k := range g.f.Kinds {
		if k == bc.KRef && r != keep && !g.borrowed[r] {
			fmt.Fprintf(&s, "\tak_release(r%d.p);\n", r)
		}
	}
	return s.String()
}

// borrowedParams reports which of f's reference parameters it borrows:
// those its code only reads (no instruction writes, moves or changes
// them, and none passes them in an argument block a callee may change),
// which it needn't retain as it starts nor release as it ends, as
// Swift's guaranteed parameters. A mut fn's receiver moves in: never
// borrowed.
func borrowedParams(m *bc.Module, f *bc.FuncDef, ins []insn) []bool {
	b := make([]bool, len(f.Kinds))
	np := int(f.NParams)
	if np > maxValueParams {
		return b
	}
	for p := range np {
		b[p] = f.Kinds[p] == bc.KRef
	}
	if f.Flags&bc.FMut != 0 && np > 0 {
		b[0] = false
	}
	no := func(r int) {
		if r >= 0 && r < np {
			b[r] = false
		}
	}
	for _, in := range ins {
		a := in.args
		d := bc.Ops[in.op]
		// The operands a reference is only read at (borrowed by the
		// instruction, retained if it keeps it).
		var reads []int
		switch d.Name {
		case "MOVR", "GETF", "GETP", "ECASE", "LEN", "ISNONE", "UNBOX", "ISSHAPE", "TOSTR", "TASK",
			"VGET", "VTAKE", "CGET", "CPEEK", "MREAD", "AGET", "ACCC", "ACCF", "MEMO", "CELL", "CELLK", "CTAKE":
			reads = []int{1}
		case "IDX", "MGET", "MGETJ", "EQ", "NE", "CONCAT", "LTS", "IDXF":
			reads = []int{1, 2}
		case "JNONE", "JSOME", "EFFECT", "RENDER", "CLEANUP", "RET":
			reads = []int{0}
		case "VSET", "CSET":
			reads = []int{0, 1}
		case "CALLC", "CALLU":
			reads = []int{1}
		case "SETIDX", "MSET":
			reads = []int{1, 2}
		case "SETF":
			reads = []int{2}
		case "SETIF":
			reads = []int{3}
		case "CPATH", "CLEN", "AGETP", "ACCP":
			reads = []int{1}
		}
		for k, o := range d.Operands {
			if o != bc.Reg {
				continue
			}
			ok := false
			for _, r := range reads {
				if r == k {
					ok = true
				}
			}
			if !ok {
				no(a[k])
			}
		}
		// What's in an argument block a call may change.
		if bs, n := callBlock(m, in); n > 0 {
			for r := bs; r < bs+n; r++ {
				no(r)
			}
		}
	}
	return b
}

// callBlock is the argument block of a call instruction (its first
// register and count): what the callee may change in place.
func callBlock(m *bc.Module, in insn) (int, int) {
	a := in.args
	switch bc.Ops[in.op].Name {
	case "CALL", "CALLB", "CALLC", "CALLU", "CALLI":
		return a[2], a[3]
	}
	return 0, 0
}

// handlerAt is the label an error thrown at pc goes to: its innermost
// handler's, else unwind.
func handlerAt(f *bc.FuncDef, pc int) string {
	for _, hd := range f.Handlers {
		if pc >= int(hd.Start) && pc < int(hd.End) {
			return fmt.Sprintf("L%d", hd.Target)
		}
	}
	return "unwind"
}

// inlined is where an error in instruction pc goes first when pc is in a
// function's body the optimizer inlined (bytecode.Inline): a trampoline
// that tells ak_frame_hook of each inlined frame it leaves, innermost
// first, with its line, then goes on to h with the line of the call
// (what a call's frame would have said), as the VM's traceback does. The
// trampoline is written by the returned func, after the instruction
// (when its code goes there); h is returned as it is when pc isn't
// inlined.
func (g *gen) inlined(f *bc.FuncDef, pc int, h string) (string, func()) {
	var ins []bc.Inline
	for _, in := range f.Inlines {
		if pc >= int(in.Start) && pc < int(in.End) {
			ins = append(ins, in)
		}
	}
	if len(ins) == 0 {
		return h, func() {}
	}
	label := fmt.Sprintf("I%d", pc)
	return label, func() {
		g.out.WriteString(fmt.Sprintf("\tif (0) {\n%s:\n", label))
		for i, in := range ins {
			callee := &g.m.Funcs[in.Func]
			if i > 0 {
				g.w("\tat_ = %d;", ins[i-1].Line)
			}
			g.w("\tak_cg_unwind(%s, %s, at_);", cbytes(callee.Name), cbytes(callee.File))
		}
		g.w("\tat_ = %d; %s\n\t}", ins[len(ins)-1].Line, g.to(h))
	}
}

// resumes are the pcs a resumable function's frame may resume at: an
// AWAIT's own (it runs again), and what follows a YIELD or a call that
// may push a frame. A call's is mapped to the call: the frame resumes
// there when the call returned or threw.
func (g *gen) resumes(f *bc.FuncDef, ins []insn) (map[int]*insn, error) {
	r := map[int]*insn{}
	for k := range ins {
		in := &ins[k]
		next := in.pc + in.op.Width()
		switch bc.Ops[in.op].Name {
		case "AWAIT":
			if _, ok := r[in.pc]; !ok {
				r[in.pc] = nil
			}
			continue
		case "YIELD":
		case "CALL":
			if g.body[in.args[1]] == syncBody {
				continue
			}
		case "CALLC", "CALLI":
		default:
			continue
		}
		if next >= len(f.Code) {
			return nil, fmt.Errorf("%s at %d is the last instruction", bc.Ops[in.op].Name, in.pc)
		}
		if bc.Ops[in.op].Name == "YIELD" {
			if _, ok := r[next]; !ok {
				r[next] = nil
			}
			continue
		}
		r[next] = in
	}
	return r, nil
}

// cbytes is s as a C string literal, byte by byte: what isn't printable
// ASCII as an octal escape, which ends after three digits (a hex one
// would take the digits after it), and ? so that no trigraph forms.
func cbytes(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c < 32 || c > 126 || c == '"' || c == '\\' || c == '?' {
			fmt.Fprintf(&b, "\\%03o", c)
		} else {
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func flit(v float64) string {
	switch {
	case math.IsNaN(v):
		return "NAN"
	case math.IsInf(v, 1):
		return "INFINITY"
	case math.IsInf(v, -1):
		return "(-INFINITY)"
	}
	return fmt.Sprintf("%#x", v) // hex float: exact
}

func ilit(v int64) string {
	if v == math.MinInt64 {
		return "INT64_MIN"
	}
	return fmt.Sprintf("INT64_C(%d)", v)
}

// leave is C that moves the registers back into the frame, which
// resumes at pc: a resumable function leaving it waiting.
func (g *gen) leave(pc int) string {
	var s strings.Builder
	s.WriteString("{ ak_val *S_ = co->regs + co->frames[fi_].base; AK_UNUSED(S_); ")
	if g.array {
		fmt.Fprintf(&s, "memcpy(S_, R, sizeof R); co->frames[fi_].pc = %d; }", pc)
		return s.String()
	}
	for r := range g.f.Kinds {
		fmt.Fprintf(&s, "S_[%d] = %s; ", r, g.r(r))
	}
	fmt.Fprintf(&s, "co->frames[fi_].pc = %d; }", pc)
	return s.String()
}

// acall is C for a call (in) that pushes a frame on the coroutine, as
// the interpreter's does: fn (a C expression, the ak_func) with clos.
// The callee runs at once when it can (ak_op_acall); when it suspended,
// or the run loop is to run it, this frame leaves too, to resume after
// the call (resumes).
func (g *gen) acall(f *bc.FuncDef, in insn, h, fn, clos string) {
	a := in.args
	at := lineAt(f, in.pc)
	next := in.pc + in.op.Width()
	g.w("{ const ak_func *g_ = %s; ak_closure *cl_ = %s;", fn, clos)
	g.w("  { %s if (!ak_op_apush(co, g_, cl_, B_, %d, %d, %d)) { at_ = %d; %s } }", g.block(a[2], a[3]), a[3], a[0], in.pc, at, g.to(h))
	g.w("  ak_val v_ = {0}; int s_ = ak_op_acall(co, &v_, AK_CG_LIM);")
	g.w("  if (s_ == AK_RUN_THROW) { at_ = %d; %s }", at, g.to(h))
	g.w("  if (s_ != AK_RUN_RET) { %s return s_; }", g.leave(next))
	g.w("  %s }", g.putKind(a[0], "v_", "g_->ret"))
}

// putKind is put for a result whose kind is a C expression's (a callee
// found at run time).
func (g *gen) putKind(a int, v, kind string) string {
	if a == bc.None {
		return fmt.Sprintf("ak_release_val(%s, (ak_kind)(%s));", v, kind)
	}
	return g.put(a, v, bc.KVoid)
}

// lineAt is the source line of f's code at pc.
func lineAt(f *bc.FuncDef, pc int) uint32 {
	var line uint32
	for _, l := range f.Lines {
		if int(l.PC) > pc {
			break
		}
		line = l.Line
	}
	return line
}

// pathArgs counts the arguments a state path (vm/path.h) reads from its
// argument registers: an index's, a key's, a member's, and a write's old
// value (and, after a key, whether it was there).
func pathArgs(p string) int {
	n := 0
	key := false
	for j := 0; j < len(p); {
		s := p[j]
		j++
		last := key
		key = false
		switch s {
		case 'f', 'F':
			j += 2
		case 'i', 'g', 'I':
			n++
		case 'k', 'v', 'h', 'm':
			j++
			n++
			key = s == 'k'
		case 'o':
			n++
			if last {
				n++
			}
			return n
		case 'r', 'a':
			return n
		}
	}
	return n
}
