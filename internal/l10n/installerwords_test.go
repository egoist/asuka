// installerKeys are the Windows installer's words: its own (the keys
// installer*) and the buttons it shares with the hosts.
func installerKeys(t *testing.T) []string {
	data, err := fs.ReadFile(FS(), "en.json")
	if err != nil {
		t.Fatal(err)
	}
	var m map[string]any
	if err := json.Unmarshal(data, &m); err != nil {
		t.Fatal(err)
	}
	keys := []string{"cancel", "close"}
	var own []string
	for k := range m {
		if strings.HasPrefix(k, "installer") {
			own = append(own, k)
		}
	}
	slices.Sort(own)
	return append(keys, own...)
}

// wordConst is a key's name in the installer's C: installerAppOpen is
// W_APP_OPEN.
func wordConst(key string) string {
	key = strings.TrimPrefix(key, "installer")
	var b strings.Builder
	b.WriteString("W_")
	for i, r := range key {
		if unicode.IsUpper(r) && i > 0 {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToUpper(r))
	}
	return b.String()
}

// TestInstallerWords checks that platform/windows/installer/words.h, the
// Windows installer's and uninstaller's words in each language Asuka is
// translated to, is the catalogs' (C can't read this package's
// catalogs: it carries its own copy). -update-words writes it.
func TestInstallerWords(t *testing.T) {
	files, err := fs.Glob(FS(), "*.json")
	if err != nil {
		t.Fatal(err)
	}
	var tags []string
	for _, f := range files {
		tags = append(tags, strings.TrimSuffix(f, ".json"))
	}
	slices.Sort(tags)
	keys := installerKeys(t)
	placeholder := regexp.MustCompile(`\{[^{}]*\}`)
	var b strings.Builder
	b.WriteString("// Code generated by internal/l10n's TestInstallerWords (go test ./internal/l10n -run InstallerWords -update-words). DO NOT EDIT.\n\n")
	b.WriteString("// The installer's words, by language: internal/l10n's catalogs'. Their\n// placeholders ({app}, {path}) are filled by name.\n\n")
	b.WriteString("enum {\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%s,\n", wordConst(k))
	}
	b.WriteString("\tW_COUNT\n};\n\n")
	b.WriteString("typedef struct {\n\tconst char *tag;  // the catalog's language: en, pt-PT, zh-Hans\n\tconst char *w[W_COUNT];  // NULL where it has none: English's then\n} word_lang;\n\n")
	b.WriteString("static const word_lang word_langs[] = {\n")
	for _, tag := range tags {
		data, err := fs.ReadFile(FS(), tag+".json")
		if err != nil {
			t.Fatal(err)
		}
		var m map[string]any
		if err := json.Unmarshal(data, &m); err != nil {
			t.Fatal(err)
		}
		fmt.Fprintf(&b, "\t{%s, {", cQuote(tag))
		for i, k := range keys {
			if i > 0 {
				b.WriteString(", ")
			}
			s, ok := m[k].(string)
			if !ok {
				b.WriteString("0")
				continue
			}
			for _, p := range placeholder.FindAllString(s, -1) {
				if strings.ContainsAny(p, ", ") {
					t.Fatalf("%s's %s: %s isn't a plain placeholder, which the installer fills by name", tag, k, p)
				}
			}
			b.WriteString(cQuote(s))
		}
		b.WriteString("}},\n")
	}
	b.WriteString("};\n")
	path := filepath.Join("..", "..", "platform", "windows", "installer", "words.h")
	if *updateWords {
		if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	have, err := os.ReadFile(path)
	if err != nil || string(have) != b.String() {
		t.Fatalf("%s isn't the catalogs' words: go test ./internal/l10n -run InstallerWords -update-words", path)
	}
}
