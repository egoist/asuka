package l10n

import (
	"encoding/json"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"testing"
	"unicode"
)

var updateWords = flag.Bool("update-words", false, "rewrite the copies of the catalogs' words (sdk/update/words.asuka, sdk/camera/desktop/camera_words.c, platform/windows/installer/words.h)")

// updateKeys are the words of platform/update's window, in Asuka's catalogs.
var updateKeys = []string{
	"ok", "cancel", "checkForUpdates", "softwareUpdate", "updateChecking", "updateUpToDate", "updateUpToDateMessage",
	"updateAvailable", "updateAvailableMessage", "updateReleaseNotes", "updateAutomatically", "updateSkip",
	"updateRemindLater", "updateInstall", "updateDownloading", "updateProgress", "updateInstalling", "updateReady",
	"updateReadyMessage", "updateRelaunch", "updateNotNow", "updateError", "updateCheckError", "updateInstallError",
	"updateUnavailable", "updateUnavailableMessage",
}

// TestUpdateWords checks that sdk/update/words.asuka, the update window's
// words in each language Asuka is translated to, is the catalogs' (an
// Asuka package can't read this package's catalogs: it carries its own
// copy). -update-words writes it.
func TestUpdateWords(t *testing.T) {
	files, err := fs.Glob(FS(), "*.json")
	if err != nil {
		t.Fatal(err)
	}
	placeholder := regexp.MustCompile(`\{[^{}]*\}`)
	var b strings.Builder
	b.WriteString("// Code generated by internal/l10n's TestUpdateWords (go test ./internal/l10n -update-words). DO NOT EDIT.\n\n")
	b.WriteString("// The update window's words, by language: internal/l10n's catalogs'.\nlet words: [string: [string: string]] = [\n")
	var tags []string
	for _, f := range files {
		tags = append(tags, strings.TrimSuffix(f, ".json"))
	}
	slices.Sort(tags)
	for _, tag := range tags {
		data, err := fs.ReadFile(FS(), tag+".json")
		if err != nil {
			t.Fatal(err)
		}
		var m map[string]any
		if err := json.Unmarshal(data, &m); err != nil {
			t.Fatal(err)
		}
		var entries []string
		for _, k := range updateKeys {
			s, ok := m[k].(string)
			if !ok {
				continue // English, then
			}
			for _, p := range placeholder.FindAllString(s, -1) {
				if strings.ContainsAny(p, ", ") {
					t.Fatalf("%s's %s: %s isn't a plain placeholder, which the package fills by name", tag, k, p)
				}
			}
			entries = append(entries, fmt.Sprintf("    %s: %s,\n", quote(k), quote(s)))
		}
		if len(entries) == 0 {
			continue
		}
		fmt.Fprintf(&b, "  %s: [\n%s  ],\n", quote(tag), strings.Join(entries, ""))
	}
	b.WriteString("]\n")
	path := filepath.Join("..", "..", "sdk", "update", "words.asuka")
	if *updateWords {
		if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	have, err := os.ReadFile(path)
	if err != nil || string(have) != b.String() {
		t.Fatalf("%s isn't the catalogs' words: go test ./internal/l10n -run UpdateWords -update-words", path)
	}
}

// quote is an Asuka string literal of s.
func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"' || r == '\\' || r == '{' || r == '}':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r == '\n':
			b.WriteString(`\n`)
		case !unicode.IsPrint(r):
			fmt.Fprintf(&b, `\u{%x}`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
